"""Build the 12-dot ruby font: gen_font12.py [--dump] [--fonts DIR] [--output FILE].

Glyphs come from Shinonome 12 dots: shnm6x12a (ASCII, 6 wide) and shnmk12
(JIS X 0208, 12 wide), both public domain (fonts/COPYRIGHT.xfonts-shinonome).
Defaults are fonts/ (data/fonts/ in the public copy) and build/font12.inc. Fails when either .pcf.gz
is missing; there is deliberately no substitute font. Only the standard
library is used; the PCF reader is shared with tools/gen_font.py.
"""
import argparse
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location('gen_font', HERE/'gen_font.py')
gen_font = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen_font)


def build(fonts):
    for name in ('shnm6x12a.pcf.gz', 'shnmk12.pcf.gz'):
        if not (fonts/name).is_file():
            raise SystemExit(f'gen_font12.py: missing {fonts/name} (Shinonome 12 dots)')
    ascii_ = gen_font.PCF(fonts/'shnm6x12a.pcf.gz')
    japanese = gen_font.PCF(fonts/'shnmk12.pcf.gz')
    glyphs = {}
    for code in range(32, 127):
        rows = ascii_.glyph(code, 6)
        if rows is not None:
            glyphs[code] = (6, rows[:12])
    for encoding in japanese.encodings:
        try:
            char = bytes([(encoding >> 8) | 0x80, (encoding & 255) | 0x80]).decode('euc_jp')
        except UnicodeError:
            continue
        if len(char) == 1:
            rows = japanese.glyph(encoding, 12)
            if rows is not None:
                glyphs[ord(char)] = (12, rows[:12])
    for required in 'A?あア漢ー々':
        if ord(required) not in glyphs:
            raise SystemExit(f'gen_font12.py: missing required glyph {required}')
    if not any(glyphs[ord('あ')][1]):
        raise SystemExit('gen_font12.py: blank glyph for あ')
    return glyphs


def main():
    root = HERE.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fonts', type=Path, default=gen_font.fonts_dir(root))
    parser.add_argument('--output', type=Path, default=root/'build/font12.inc')
    parser.add_argument('--dump', action='store_true')
    args = parser.parse_args()
    glyphs = build(args.fonts)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.output.with_name(args.output.name + '.tmp')
    with tmp.open('w', encoding='ascii') as output:
        output.write('/* Generated by tools/gen_font12.py; do not edit. */\n')
        output.write('static const Font12Glyph font12_glyphs[] = {\n')
        for code, (width, rows) in sorted(glyphs.items()):
            output.write('    {0x%Xu, %d, {%s}},\n' %
                         (code, width, ','.join('0x%03Xu' % row for row in rows)))
        output.write('};\n')
    tmp.replace(args.output)
    if args.dump:
        for char in 'Aあ漢ー':
            width, rows = glyphs[ord(char)]
            print(char)
            for row in rows:
                print(''.join('#' if row & (1 << (width-1-x)) else '.' for x in range(width)))


if __name__ == '__main__':
    main()
