"""Generate portable C tables from Python's standard Japanese codecs."""
import argparse
from pathlib import Path


def scalar(data, codec):
    try:
        text = data.decode(codec)
        return ord(text) if len(text) == 1 else 0
    except UnicodeDecodeError:
        return 0


def table(out, name, values):
    out.write(f'static const uint32_t {name}[{len(values)}] = {{\n')
    for pos in range(0, len(values), 12):
        out.write('    ' + ','.join(f'0x{x:x}' for x in values[pos:pos+12]) + ',\n')
    out.write('};\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    jis0208 = [scalar(bytes([a, b]), 'euc_jp')
               for a in range(0xa1, 0xff) for b in range(0xa1, 0xff)]
    jis0212 = [scalar(bytes([0x8f, a, b]), 'euc_jp')
               for a in range(0xa1, 0xff) for b in range(0xa1, 0xff)]
    cp932 = [scalar(bytes([a, b]), 'cp932')
             for a in list(range(0x81, 0xa0)) + list(range(0xe0, 0xfd))
             for b in range(0x40, 0xfd)]
    # Use codec-selected canonical bytes for duplicate Unicode mappings.
    reverse = {}
    for code in set(jis0208 + jis0212 + cp932):
        if not code:
            continue
        result = []
        for codec in ('cp932', 'euc_jp'):
            try:
                data = chr(code).encode(codec)
                result.append(int.from_bytes(data, 'big'))
            except UnicodeEncodeError:
                result.append(0)
        reverse[code] = result
    # Include single-byte and codec-specific Unicode aliases (yen/backslash,
    # overline/tilde, CP932 compatibility mappings).
    for code in list(range(256)) + [0x203e, 0x301c, 0x2016, 0x2212, 0xa2, 0xa3, 0xac] + list(range(0xff61, 0xffa0)):
        result = []
        for codec in ('cp932', 'euc_jp'):
            try:
                result.append(int.from_bytes(chr(code).encode(codec), 'big'))
            except UnicodeEncodeError:
                result.append(0)
        reverse[code] = result
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open('w', encoding='ascii') as out:
        out.write('/* Generated by tools/gen_jis.py; do not edit. */\n')
        table(out, 'jis0208', jis0208)
        table(out, 'jis0212', jis0212)
        table(out, 'jis_cp932', cp932)
        out.write('typedef struct { uint32_t unicode, sjis, euc; } JisReverse;\n')
        out.write('static const JisReverse jis_reverse[] = {\n')
        for code, (sjis, euc) in sorted(reverse.items()):
            out.write(f'    {{0x{code:x},0x{sjis:x},0x{euc:x}}},\n')
        out.write('};\n')


if __name__ == '__main__':
    main()
