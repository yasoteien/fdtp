"""FDTP's icon (revision 1 item 23): gen_icon.py [--output FILE] [--png-dir DIR] [--preview FILE].

FD's screen colours: a navy (#000055) square with rounded corners, a cyan
(#00FFFF) rounded frame and yellow (#FFFF00) letters, "FD" at 16 and 32
pixels, "FD" over "TP" from 48 up. Every size is drawn in its own dots (the
letters are a 5 x 7 dot font times a whole number), never scaled down, so
nothing blurs. Outside the rounded corners is transparent.

  --output FILE   the C array for _NET_WM_ICON (default build/icon_data.inc):
                  static const uint32_t fdtp_icon[] = { w, h, ARGB..., w, h, ... };
  --png-dir DIR   fdtp-16.png ... fdtp-128.png (the committed ones: icons/, data/icons/ in the public copy)
  --preview FILE  every size side by side, 4 times larger (to look at)
Only the standard library is used.
"""
import argparse
from pathlib import Path
import struct
import zlib

HERE = Path(__file__).resolve().parent
NAVY, CYAN, YELLOW, CLEAR = 0xFF000055, 0xFF00FFFF, 0xFFFFFF00, 0x00000000

# 5 x 7 dots, '#' = on.
GLYPHS = {
    'F': ['#####', '#....', '#....', '####.', '#....', '#....', '#....'],
    'D': ['####.', '#...#', '#...#', '#...#', '#...#', '#...#', '####.'],
    'T': ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '..#..'],
    'P': ['####.', '#...#', '#...#', '####.', '#....', '#....', '#....'],
}

# size: (frame width, corner radius, rows of letters, dot scale, letter gap, row gap)
SIZES = {
    16: (1, 3, ['FD'], 1, 1, 0),
    32: (2, 6, ['FD'], 2, 2, 0),
    48: (2, 8, ['FD', 'TP'], 2, 2, 4),
    64: (3, 11, ['FD', 'TP'], 3, 3, 5),
    128: (5, 22, ['FD', 'TP'], 6, 6, 10),
}


def inside_rounded(x, y, left, top, right, bottom, radius):
    """Is the centre of pixel (x, y) inside the rounded rectangle [left, right) x [top, bottom)?"""
    cx, cy = x + 0.5, y + 0.5
    if not (left <= cx < right and top <= cy < bottom):
        return False
    radius = max(radius, 0)
    nx = min(max(cx, left + radius), right - radius)
    ny = min(max(cy, top + radius), bottom - radius)
    return (cx - nx) ** 2 + (cy - ny) ** 2 <= radius ** 2


def draw(size):
    frame, radius, rows, scale, gap, row_gap = SIZES[size]
    px = [[CLEAR] * size for _ in range(size)]
    for y in range(size):
        for x in range(size):
            if inside_rounded(x, y, 0, 0, size, size, radius):
                inner = inside_rounded(x, y, frame, frame, size - frame, size - frame, radius - frame)
                px[y][x] = NAVY if inner else CYAN
    glyph_w, glyph_h = 5 * scale, 7 * scale
    widths = [len(r) * glyph_w + (len(r) - 1) * gap for r in rows]
    height = len(rows) * glyph_h + (len(rows) - 1) * row_gap
    top = (size - height) // 2
    for i, text in enumerate(rows):
        left = (size - widths[i]) // 2
        y0 = top + i * (glyph_h + row_gap)
        for j, ch in enumerate(text):
            x0 = left + j * (glyph_w + gap)
            for gy, line in enumerate(GLYPHS[ch]):
                for gx, dot in enumerate(line):
                    if dot != '#':
                        continue
                    for dy in range(scale):
                        for dx in range(scale):
                            px[y0 + gy * scale + dy][x0 + gx * scale + dx] = YELLOW
    # The letters stay off the frame.
    for y in range(size):
        for x in range(size):
            if px[y][x] == YELLOW:
                assert inside_rounded(x, y, frame, frame, size - frame, size - frame, radius - frame), (size, x, y)
    return px


def png(px):
    h, w = len(px), len(px[0])
    raw = b''.join(b'\0' + b''.join(struct.pack('>BBBB', (p >> 16) & 255, (p >> 8) & 255, p & 255, p >> 24)
                                     for p in row) for row in px)

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xFFFFFFFF)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def c_array(images):
    words = []
    for size, px in images:
        words += [size, size] + [p for row in px for p in row]
    lines = ['/* Generated by fdtp/tools/gen_icon.py: _NET_WM_ICON, sizes ' +
             ' '.join(str(s) for s, _ in images) + '. Do not edit. */',
             'static const uint32_t fdtp_icon[%d] = {' % len(words)]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08Xu' % v for v in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def preview(images, zoom=4, pad=8):
    width = sum(s * zoom + pad for s, _ in images) + pad
    height = max(s for s, _ in images) * zoom + 2 * pad
    sheet = [[0xFF808080] * width for _ in range(height)]
    x0 = pad
    for size, px in images:
        for y in range(size * zoom):
            for x in range(size * zoom):
                p = px[y // zoom][x // zoom]
                if p >> 24:
                    sheet[pad + y][x0 + x] = p
        x0 += size * zoom + pad
    return sheet


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--output', type=Path)
    ap.add_argument('--png-dir', type=Path)
    ap.add_argument('--preview', type=Path)
    args = ap.parse_args()
    if not (args.output or args.png_dir or args.preview):
        args.output = HERE.parent / 'build' / 'icon_data.inc'
    images = [(size, draw(size)) for size in sorted(SIZES)]
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        tmp = args.output.with_name(args.output.name + '.tmp')
        tmp.write_text(c_array(images))
        tmp.replace(args.output)
    if args.png_dir:
        args.png_dir.mkdir(parents=True, exist_ok=True)
        for size, px in images:
            (args.png_dir / f'fdtp-{size}.png').write_bytes(png(px))
    if args.preview:
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        args.preview.write_bytes(png(preview(images)))


if __name__ == '__main__':
    main()
